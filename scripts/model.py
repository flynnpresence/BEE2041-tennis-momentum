# ── Output 5: Coefficient plot ────────────────────────────────────────────────
def plot_model_table(
    atp_coef, wta_coef,
    atp_bp_ate, atp_bp_ci_lo, atp_bp_ci_hi,
    wta_bp_ate, wta_bp_ci_lo, wta_bp_ci_hi,
    atp_tb_ate, atp_tb_ci_lo, atp_tb_ci_hi,
    wta_tb_ate, wta_tb_ci_lo, wta_tb_ci_hi
) -> None:
    """
    Clean Plotly forest plot: logistic regression coefficients (symmetric
    1.96*SE, from statsmodels' cluster-robust SE) plus causal forest ATE rows
    for BP and TB (asymmetric error bars drawn directly from the
    match-clustered bootstrap's percentile CI, not +-1.96*SE -- the WTA
    forest specs' bootstrap distributions are visibly left-skewed, so a
    symmetric SE-based bar would disagree with the reported [ci_lo, ci_hi]).
    """
    import plotly.graph_objects as go

    label_map = LABEL_MAP

    atp_coef = atp_coef.copy()
    wta_coef = wta_coef.copy()
    # Exclude raw feature names before mapping
    exclude_raw = {'const', 'HL_Win', 'High_Leverage'}
    atp_coef = atp_coef[~atp_coef['Feature'].isin(exclude_raw)].copy()
    wta_coef = wta_coef[~wta_coef['Feature'].isin(exclude_raw)].copy()
    atp_coef['Feature'] = atp_coef['Feature'].replace(label_map)
    wta_coef['Feature'] = wta_coef['Feature'].replace(label_map)

    # Build rows: logistic regression coefficients
    features = atp_coef['Feature'].tolist()

    rows = []
    for feat in features:
        atp_row = atp_coef[atp_coef['Feature'] == feat]
        wta_row = wta_coef[wta_coef['Feature'] == feat]
        if len(atp_row) == 0 or len(wta_row) == 0:
            continue
        rows.append({
            'label': feat,
            'atp_coef': atp_row['Coef'].values[0],
            'atp_se':   atp_row['SE'].values[0],
            'wta_coef': wta_row['Coef'].values[0],
            'wta_se':   wta_row['SE'].values[0],
            'type': 'logistic'
        })

    # Add causal forest rows (CI bounds, not SE -- see docstring)
    rows.append({
        'label': 'Break Point Win',
        'atp_coef': atp_bp_ate, 'atp_ci_lo': atp_bp_ci_lo, 'atp_ci_hi': atp_bp_ci_hi,
        'wta_coef': wta_bp_ate, 'wta_ci_lo': wta_bp_ci_lo, 'wta_ci_hi': wta_bp_ci_hi,
        'type': 'forest'
    })
    rows.append({
        'label': 'Tiebreak Win',
        'atp_coef': atp_tb_ate, 'atp_ci_lo': atp_tb_ci_lo, 'atp_ci_hi': atp_tb_ci_hi,
        'wta_coef': wta_tb_ate, 'wta_ci_lo': wta_tb_ci_lo, 'wta_ci_hi': wta_tb_ci_hi,
        'type': 'forest'
    })

    # Y axis: reversed so top row appears first
    y_labels = [r['label'] for r in rows][::-1]

    fig = go.Figure()

    def error_x_kwargs(coef, row, side):
        """Forest rows: asymmetric bar from the bootstrap percentile CI.
        Logistic rows: symmetric 1.96*SE (statsmodels cluster-robust SE)."""
        if row['type'] == 'forest':
            ci_lo, ci_hi = row[f'{side}_ci_lo'], row[f'{side}_ci_hi']
            return dict(type='data', symmetric=False,
                       array=[ci_hi - coef], arrayminus=[coef - ci_lo])
        se = row[f'{side}_se']
        return dict(type='data', array=[1.96 * se])

    def ci_bounds(coef, row, side):
        if row['type'] == 'forest':
            return row[f'{side}_ci_lo'], row[f'{side}_ci_hi']
        se = row[f'{side}_se']
        return coef - 1.96 * se, coef + 1.96 * se

    for i, row in enumerate(rows[::-1]):
        symbol = 'diamond' if row['type'] == 'forest' else 'circle'
        y_pos = i

        # ATP
        atp_lo, atp_hi = ci_bounds(row['atp_coef'], row, 'atp')
        fig.add_trace(go.Scatter(
            x=[row['atp_coef']],
            y=[y_pos - 0.15],
            error_x=dict(
                **error_x_kwargs(row['atp_coef'], row, 'atp'),
                visible=True,
                color='rgba(74,144,217,0.6)',
                thickness=1.5,
                width=5
            ),
            mode='markers',
            marker=dict(
                symbol=symbol,
                size=10,
                color='#4a90d9',
                line=dict(width=1.5, color='white')
            ),
            name='ATP',
            showlegend=(i == 0),
            hovertemplate=f"<b>ATP: {row['label']}</b><br>"
                          f"Effect: {row['atp_coef']:.4f}<br>"
                          f"95% CI: [{atp_lo:.4f}, {atp_hi:.4f}]"
                          f"<extra></extra>",
            legendgroup='ATP'
        ))

        # WTA
        wta_lo, wta_hi = ci_bounds(row['wta_coef'], row, 'wta')
        fig.add_trace(go.Scatter(
            x=[row['wta_coef']],
            y=[y_pos + 0.15],
            error_x=dict(
                **error_x_kwargs(row['wta_coef'], row, 'wta'),
                visible=True,
                color='rgba(232,113,90,0.6)',
                thickness=1.5,
                width=5
            ),
            mode='markers',
            marker=dict(
                symbol=symbol,
                size=10,
                color='#e8715a',
                line=dict(width=1.5, color='white')
            ),
            name='WTA',
            showlegend=(i == 0),
            hovertemplate=f"<b>WTA: {row['label']}</b><br>"
                          f"Effect: {row['wta_coef']:.4f}<br>"
                          f"95% CI: [{wta_lo:.4f}, {wta_hi:.4f}]"
                          f"<extra></extra>",
            legendgroup='WTA'
        ))

    fig.add_vline(x=0, line_dash='dash', line_color='black',
                  line_width=1, opacity=0.5)

    fig.update_layout(
        title=dict(
            text='<b>Figure 5: Model Results: Logistic Regression + Causal Forest</b>',
            font=dict(size=14, family='Helvetica Neue, Arial, sans-serif',
                      color='#111'),
            x=0.5
        ),
        height=480,
        font=dict(family='Helvetica Neue, Arial, sans-serif', size=11,
                  color='#111'),
        paper_bgcolor='white',
        plot_bgcolor='white',
        margin=dict(l=260, r=40, t=80, b=80),
        hoverlabel=dict(bgcolor='white', font_size=12),
        legend=dict(
            orientation='v',
            x=1.02, y=1,
            bgcolor='white',
            bordercolor='#eeeeee',
            borderwidth=1
        ),
        xaxis=dict(
            title=dict(text='Effect on Win Probability',
                       font=dict(color='#111')),
            showgrid=True,
            gridcolor='#eeeeee',
            zeroline=False
        ),
        yaxis=dict(
            tickvals=list(range(len(rows))),
            ticktext=y_labels,
            showgrid=False,
            zeroline=False,
            tickfont=dict(color='#111')
        )
    )

    out_path = os.path.join(OUT_DIR, 'output5_model_table.html')
    fig.write_html(out_path, include_plotlyjs='cdn', full_html=False)
    print('  Saved output5_model_table.html')


