# ── Output 1: Per-player Chi-squared summary table ────────────────────────────
def plot_chi2_table(tests: pd.DataFrame) -> None:
    rows = []
    for tour, grp in tests.groupby('Tour'):
        n = len(grp)
        chi2_n = int(grp['Chi2_Sig'].sum())
        runs_n = int(grp['Runs_Sig'].sum())
        rows.append({
            'Tour':           tour,
            'Players Tested': n,
            'Chi² Sig. (n)':  chi2_n,
            'Chi² Sig. (%)':  f"{chi2_n / n * 100:.1f}%",
            'Runs Sig. (n)':  runs_n,
            'Runs Sig. (%)':  f"{runs_n / n * 100:.1f}%",
        })
    summary = pd.DataFrame(rows)

    html_table = summary.to_html(
        index=False, border=0, classes='momentum-table')
    full_html = (
        '<!DOCTYPE html><html><head><meta charset="utf-8">'
        '<style>'
        'body{margin:0;padding:16px;font-family:Inter,sans-serif;}'
        '.table-container{overflow-x:auto;}'
        'table.momentum-table{width:100%;border-collapse:collapse;font-size:14px;}'
        'table.momentum-table th{background:#f0f0ec;font-weight:600;padding:10px 14px;'
        'text-align:left;border-bottom:2px solid #d0d0cc;color:#1a1a1a;}'
        'table.momentum-table td{'
        'padding:9px 14px;border-bottom:1px solid #e8e8e4;color:#1a1a1a;}'
        'table.momentum-table tr:last-child td{border-bottom:none;}'
        '</style></head><body>'
        '<p style="font-family:Inter,sans-serif;font-size:14px;font-weight:600;'
        'margin:0 0 8px 0;color:#1a1a1a;font-weight:bold;">Figure 1: Independence Tests: '
        'Chi-squared and Runs Test Results</p>'
        '<div class="table-container">' + html_table + '</div>'
        '</body></html>'
    )

    out_path = os.path.join(OUT_DIR, 'output1_chi2_table.html')
    with open(out_path, 'w', encoding='utf-8') as f:
        f.write(full_html)
    print('  Saved output1_chi2_table.html')


# ── Output 2: CUSUM line chart ────────────────────────────────────────────────
def plot_cusum(df: pd.DataFrame, tour_name: str) -> None:
    import plotly.graph_objects as go

    match_counts = df.groupby('match_id').size()
    target_match = match_counts.idxmax()
    match_data = df[df['match_id'] == target_match].copy().reset_index(drop=True)
    match_row = df[df['match_id'] == target_match].iloc[0]
    p1 = match_row['Focal_Player']
    p2 = match_row['Opponent_Player']

    x = match_data.index.tolist()
    y = match_data['CUSUM'].tolist()

    def leverage_label(row):
        if row.get('High_Leverage_TB', 0) == 1:
            return 'Tiebreak point'
        elif row.get('High_Leverage_BP', 0) == 1:
            return 'Break point'
        elif row.get('High_Leverage', 0) == 1:
            return 'High leverage'
        return 'Standard point'

    hover = [
        f'Point {i+1}<br>'
        f'CUSUM: {row["CUSUM"]:.3f}<br>{leverage_label(row)}'
        for i, (_, row) in enumerate(match_data.iterrows())
    ]

    fig = go.Figure()

    fig.add_trace(go.Scatter(
        x=x, y=[max(v, 0) for v in y],
        fill='tozeroy',
        fillcolor='rgba(74,175,74,0.25)',
        line=dict(width=0),
        showlegend=True,
        name='Above expectation',
        hoverinfo='skip'
    ))

    fig.add_trace(go.Scatter(
        x=x, y=[min(v, 0) for v in y],
        fill='tozeroy',
        fillcolor='rgba(205,92,92,0.25)',
        line=dict(width=0),
        showlegend=True,
        name='Below expectation',
        hoverinfo='skip'
    ))

    fig.add_trace(go.Scatter(
        x=x, y=y,
        mode='lines',
        line=dict(color='#444444', width=1.2),
        showlegend=False,
        hovertext=hover,
        hoverinfo='text',
        name='CUSUM'
    ))

    fig.add_hline(y=0, line_dash='dash', line_color='black',
                  line_width=0.8, opacity=0.5)

    fig.update_layout(
        title=dict(
            text=(f'<b>Figure 2: Cumulative Momentum Score: {tour_name}</b><br>'
                  f'<span style="font-size:11px">{p1} vs {p2}</span>'),
            font=dict(size=13, family='Helvetica Neue, Arial, sans-serif',
                      color='#111'),
            x=0.5
        ),
        height=380,
        font=dict(family='Helvetica Neue, Arial, sans-serif',
                  size=11, color='#111'),
        paper_bgcolor='white',
        plot_bgcolor='white',
        margin=dict(l=60, r=40, t=90, b=60),
        hoverlabel=dict(bgcolor='white', font_size=12),
        legend=dict(
            orientation='h', x=0.5, xanchor='center', y=-0.15,
            bgcolor='white'
        ),
        xaxis=dict(title='Point Number', showgrid=False, zeroline=False),
        yaxis=dict(title='Cumulative Deviation from Mean',
                   showgrid=True, gridcolor='#eeeeee', zeroline=False)
    )

    suffix = tour_name.lower()
    out_path = os.path.join(OUT_DIR, f'output2_cusum_{suffix}.html')
    fig.write_html(out_path, include_plotlyjs='cdn', full_html=False)
    print(f'  Saved output2_cusum_{suffix}.html')


